"""متن‌های خوش‌آمد و «درباره ما».

قاعده: متن عمومی (WELCOME_PUBLIC) را هر کسی که ربات را باز کند می‌بیند، پس هیچ اطلاعات داخلی ندارد
(نه آمار پرسنل و مددجو، نه نشانی، نه امکانات داخلی ربات). متن‌های پرسنلی فقط بعد از اتصال با کد دعوت نشان داده می‌شوند.
اطلاعات تماس عمومی (در صورت تمایل) از CONTACT_TEXT در فایل .env خوانده می‌شود."""
from . import config


def public_contact() -> str:
    c = config.CONTACT_TEXT.strip()
    return f"\n\n📞 {c}" if c else ""


def welcome_public(user_id: int) -> str:
    return (
        f"🌿 <b>به ربات {config.CENTER_NAME} خوش آمدید</b>\n\n"
        "ما در کنار مددجویان و خانواده‌هایشان هستیم تا با مراقبت، احترام و تلاش مستمر، "
        "مسیر توانمندی و کیفیت بهتر زندگی را هموار کنیم.\n\n"
        "🔒 این ربات <b>اختصاصی پرسنل مرکز</b> است و برای حفظ حریم خصوصی مددجویان، "
        "بدون دعوت‌نامه رسمی در دسترس نیست.\n\n"
        "👤 همکار گرامی: کد دعوتی را که مدیریت مرکز به شما داده است همین‌جا ارسال کنید.\n"
        f"شناسه شما برای مدیریت: <code>{user_id}</code>"
        f"{public_contact()}\n\n"
        "ℹ️ اگر مددجو یا همراه ایشان هستید، لطفاً برای دریافت راهنمایی با مرکز تماس بگیرید."
    )


